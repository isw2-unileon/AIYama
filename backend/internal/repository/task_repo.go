func UpdateFlexibleTask(ctx context.Context, db *sqlx.DB, task *models.FlexibleTask) error {
	query := `
		UPDATE flexible_tasks 
		SET name = $1, duration_minutes = $2, weekly_frequency = $3, energy_level = $4, scheduled_at = $5, scheduled_end = $6
		WHERE id = $7
	`
	_, err := db.ExecContext(ctx, query,
		task.Name,
		task.DurationMinutes,
		task.WeeklyFrequency,
		task.EnergyLevel,
		task.ID,
	)
	return err
}

func DeleteFlexibleTask(ctx context.Context, db *sqlx.DB, id string, userID string) error {
	query := `
		DELETE FROM flexible_tasks 
		WHERE id = $1 AND user_id = $2
	`
	result, err := db.ExecContext(ctx, query, id, userID)
	if err != nil {
		return err
	}

	rowsAffected, err := result.RowsAffected()
	if err != nil {
		return err
	}

	if rowsAffected == 0 {
		return errors.New("task not found or unauthorized")
	}

	return nil
}
